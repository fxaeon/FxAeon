import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
const require = createRequire(resolve(import.meta.dirname, '../../mini-app/package.json'));
const { chromium, expect } = require('@playwright/test');
const origin = process.env.LANDING_URL || 'http://127.0.0.1:4355/';
const browser = await chromium.launch({ headless: true });
try {
  for (const width of [390, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 844 }, reducedMotion: 'reduce' });
    const mediaRequests = [], errors = [];
    page.on('request', request => { if (new URL(request.url()).pathname.endsWith('.mp4')) mediaRequests.push(request.url()); });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(origin, { waitUntil: 'networkidle' });
    const figure = page.locator('[data-brand-film]'), video = figure.locator('video'), button = figure.locator('button');
    await figure.scrollIntoViewIfNeeded();
    assert.equal(mediaRequests.length, 0, 'Reduced motion must not download the video');
    await expect(button).toHaveAccessibleName('Play brand film');
    await button.click();
    await expect(button).toHaveAccessibleName('Pause brand film');
    await expect.poll(() => video.evaluate(node => node.currentTime)).toBeGreaterThan(.1);
    assert.match(await video.getAttribute('src'), width < 768 ? /brand-film-mobile\.mp4\?v=/ : /brand-film\.mp4\?v=/);
    await page.screenshot({ path: resolve(import.meta.dirname, `../review/motion/film-${width}.png`) });
    await button.click();
    assert.equal(await video.evaluate(node => node.paused), true);
    await page.locator('footer').scrollIntoViewIfNeeded();
    await figure.scrollIntoViewIfNeeded();
    assert.equal(await video.evaluate(node => node.paused), true, 'An explicit pause survives scrolling');
    await button.click();
    await video.evaluate(node => { node.currentTime = node.duration - .1; });
    await expect(button).toHaveAccessibleName('Replay brand film');
    await button.click();
    await expect(button).toHaveAccessibleName('Pause brand film');
    assert.ok(await video.evaluate(node => node.currentTime < 2));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    await page.close();
  }
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'no-preference' });
  await page.goto(origin, { waitUntil: 'networkidle' });
  await page.locator('[data-brand-film]').scrollIntoViewIfNeeded();
  await expect(page.locator('[data-brand-film]')).toHaveAttribute('data-film-state', 'playing');
  await page.locator('footer').scrollIntoViewIfNeeded();
  await expect.poll(() => page.locator('[data-brand-film] video').evaluate(node => node.paused)).toBe(true);
  await page.locator('[data-brand-film]').scrollIntoViewIfNeeded();
  await expect(page.locator('[data-brand-film]')).toHaveAttribute('data-film-state', 'playing');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect.poll(() => page.locator('[data-brand-film] video').evaluate(node => node.paused)).toBe(true);
  await page.close();
  const still = await browser.newPage({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
  await still.goto(origin);
  await expect(still.locator('[data-film-toggle]')).toBeHidden();
  assert.equal(await still.locator('[data-brand-film] video').getAttribute('src'), null);
  assert.match(await still.locator('[data-brand-film] video').getAttribute('poster'), /brand-film-poster\.jpg/);
  const response = await fetch(new URL('assets/brand-film-mobile.mp4', origin), { headers: { Range: 'bytes=0-99' } });
  assert.equal(response.status, 206);
  assert.equal(response.headers.get('Content-Type'), 'video/mp4');
  assert.equal((await response.arrayBuffer()).byteLength, 100);
  const invalid = await fetch(new URL('assets/brand-film-mobile.mp4', origin), { headers: { Range: 'bytes=999999999-' } });
  assert.equal(invalid.status, 416);
  console.log('Film: responsive renditions, real playback, pause/replay, offscreen suspension, live reduced motion, no-JS poster and byte-range delivery passed');
} finally { await browser.close(); }
