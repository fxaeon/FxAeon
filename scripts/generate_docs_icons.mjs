import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// Decorative docs icons are cached in CSS instead of repeating SVG paths in
// every exported document. Regenerate after changing the locked Lucide version.
const root = resolve(import.meta.dirname, '..');
const require = createRequire(resolve(root, 'apps/mini-app/package.json'));
const { createElement } = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const lucide = require('lucide-react');
const names = ['ArrowLeft', 'ArrowLeftRight', 'ArrowRight', 'ArrowUpRight', 'BookOpen', 'CandlestickChart', 'Check', 'ChevronDown', 'CircleHelp', 'Code2', 'Copy', 'EllipsisVertical', 'Globe', 'History', 'Landmark', 'List', 'Menu', 'MessageCircle', 'Rocket', 'Search', 'Settings2', 'ShieldCheck', 'Sprout', 'Wallet'];
const license = await readFile(resolve(root, 'apps/mini-app/node_modules/lucide-react/LICENSE'), 'utf8');
const images = names.map(name => {
  const svg = renderToStaticMarkup(createElement(lucide[name], { size: 24 }));
  const paths = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>'));
  return encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${paths}</svg>`);
});
const sizes = [13, 14, 15, 18, 19, 20, 21, 22];
await writeFile(resolve(root, 'apps/mini-app/src/app/docs/DocsIcon.module.css'), `/*! Generated by scripts/generate_docs_icons.mjs.\n${license.trim()}\n*/\n:where(${names.map((_, index) => `.i${index}`).join(', ')}) { display: inline-block; flex: 0 0 auto; width: 16px; height: 16px; background-color: currentColor; mask-size: 100% 100%; mask-repeat: no-repeat; forced-color-adjust: none; }\n${names.map((_, index) => `.i${index} { mask-image: url("data:image/svg+xml,${images[index]}"); }`).join('\n')}\n${sizes.map(size => `.s${size} { width: ${size}px; height: ${size}px; }`).join('\n')}\n`);
console.log(`Generated ${names.length} cached decorative docs icons`);
